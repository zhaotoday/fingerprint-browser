import type { OpenSourceSubcategory, DirectoryCategory, SimpleResourceItem } from '../types/resource'

function parseUrlMeta(url: string): { domain: string; repoPath?: string } {
  try {
    const parsed = new URL(url)
    const domain = parsed.hostname.replace(/^www\./, '')
    if (domain === 'github.com') {
      const parts = parsed.pathname.split('/').filter(Boolean)
      if (parts.length >= 2) {
        return { domain, repoPath: `${parts[0]}/${parts[1]}` }
      }
    }
    return { domain }
  } catch {
    return { domain: 'link' }
  }
}

function makeItems(
  category: string,
  subcategory: string | undefined,
  rawList: Array<{ title: string; url: string }>,
): SimpleResourceItem[] {
  return rawList.map((entry, idx) => {
    const { domain, repoPath } = parseUrlMeta(entry.url)
    return {
      id: `${category}-${subcategory ? subcategory + '-' : ''}${idx + 1}`,
      title: entry.title,
      url: entry.url,
      category,
      subcategory,
      repoPath,
      domain,
    }
  })
}

